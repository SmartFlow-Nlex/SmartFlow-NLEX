#!/usr/bin/env node
/**
 * Writes the asset brief for every hero and companion from what the game really
 * uses: names and jobs from core/roster, shapes, colours and materials from the
 * models, sizes and pivots from the baked manifest. Run it after a bake:
 *
 *   node scripts/tollbound-art/write-briefs.js
 */
const fs = require('fs');
const os = require('os');
const path = require('path');
const ts = require('typescript');

const root = path.join(__dirname, '..', '..');
const game = path.join(root, 'frontend', 'games', 'roadTrip');
const artDir = path.join(game, 'assets', 'art');
const manifest = JSON.parse(fs.readFileSync(path.join(artDir, 'manifest.json'), 'utf8')).sprites;

// The roster is TypeScript; compile the game's core to a temp folder to read it.
const out = fs.mkdtempSync(path.join(os.tmpdir(), 'tb-briefs-'));
for (const name of fs.readdirSync(path.join(game, 'core'))) {
  if (name.endsWith('.ts')) {
    const { outputText } = ts.transpileModule(fs.readFileSync(path.join(game, 'core', name), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } });
    fs.mkdirSync(path.join(out, 'core'), { recursive: true });
    fs.writeFileSync(path.join(out, 'core', name.replace(/\.ts$/, '.js')), outputText);
  }
}
const { HERO_DEFS, SIDEKICK_DEFS, sidekickTags } = require(path.join(out, 'core', 'roster.js'));
const { HEROES, SIDEKICKS } = require(path.join(out, 'core', 'types.js'));
const { heroRule, sidekickRule, ruleProgress } = require(path.join(out, 'core', 'unlocks.js'));
const { defaultSave } = require(path.join(out, 'core', 'save.js'));

const heroScenes = require('./scenes/heroes');
const sidekickScenes = require('./scenes/sidekicks');
const { polish } = require('./scenes/polish');

// One line of silhouette from the note above each model.
function notes() {
  const found = {};
  const heroSrc = fs.readFileSync(path.join(__dirname, 'scenes', 'heroes.js'), 'utf8');
  for (const m of heroSrc.matchAll(/^\/\/ -- (.+?)\s*-+\s*$/gm)) {
    const id = m[1].split(/[ :(]/).find((w) => /^[A-Z]/.test(w) && w !== 'Kuya');
    found[id.toLowerCase()] = m[1].replace(/\(.*?\)\.?\s*/, '').replace(/^[^.:]*[:.]\s*/, '');
  }
  const skSrc = fs.readFileSync(path.join(__dirname, 'scenes', 'sidekicks.js'), 'utf8');
  for (const m of skSrc.matchAll(/^\/\*\* ([A-Z][a-z]+): (.+?) \*\/\s*\nfunction (\w+)/gm)) {
    found[m[3]] = m[2];
  }
  const navie = fs.readFileSync(path.join(__dirname, 'scenes', 'navie.js'), 'utf8').match(/\/\*\* Navie: (.+?) \*\//);
  found.navie = navie !== null ? navie[1] : '';
  return found;
}

/** Roughly how much of the model a part shows, so the palette lists the body colour before the bolts. */
function area(p) {
  const a = p.args;
  switch (p.type) {
    case 'sphere':
      return a[0] * a[0];
    case 'ell':
    case 'box':
      return a[0] * a[1] + a[1] * a[2] + a[0] * a[2];
    case 'cyl':
      return a[0] * (a[0] + a[1]);
    case 'cap':
      return a[6] * Math.hypot(a[3] - a[0], a[4] - a[1], a[5] - a[2]);
    case 'tor':
      return a[0] * a[1];
    case 'cone':
      return Math.max(a[0], a[1]) * a[2];
    default:
      return 0.1;
  }
}

function look(parts) {
  const colours = new Map();
  const mats = new Set();
  for (const p of parts) {
    if (p.op === 'sub') {
      continue;
    }
    const key = p.color.toUpperCase();
    colours.set(key, (colours.get(key) ?? 0) + area(p));
    mats.add(p.mat);
  }
  const top = [...colours.entries()].sort((a, b) => b[1] - a[1]).slice(0, 5).map(([c]) => c);
  return { palette: top.join(' '), materials: [...mats].sort().join(', ') };
}

const sprite = (name) => {
  const s = manifest[name];
  if (s === undefined) {
    throw new Error(`Not in the manifest: ${name}`);
  }
  return `\`${name}.webp\` ${s.w}x${s.h}, pivot (${Math.round(s.ax)}, ${Math.round(s.ay)}), ${s.ppu.toFixed(0)} px/unit`;
};

const save = defaultSave();
const howToEarn = (rule, plain) => (rule !== null ? ruleProgress(save, rule).text : plain);
const NOTES = notes();
const lines = [];
const line = (s = '') => lines.push(s);

line('# Tollbound Heroes: asset briefs and manifest');
line();
line('Generated by `node scripts/tollbound-art/write-briefs.js` from the roster, the models and `manifest.json`. Do not edit by hand.');
line();
line('**How the art is made.** Every character is an original signed-distance clay model in `scripts/tollbound-art/scenes/`, ray-marched by `scripts/tollbound-art/render.js` and packed to WebP by `bake.js` (`node scripts/tollbound-art/bake.js`). Nothing is taken from another game or from stock art.');
line();
line('**Scale and pivot.** One model unit is about a third of a small car. `px/unit` is the bake scale; the pivot is where the sprite meets the ground, in sprite pixels from its top left. `wide` is the car width in model units; the road scales each hero so that width equals its real lane share, whatever the sprite size.');
line();
line('**Faces.** Eyes, lids, smile, blush and lamps are sculpted into the model (`scenes/sculpt.js`). `web/art/clayFaces.ts` adds only what moves, clipped to the lid openings the bake measured: iris, pupil and closing lids.');
line();
line('## Animation states (all characters, driven at run time)');
line();
line('| Who | State | How it shows |');
line('| --- | --- | --- |');
line('| Hero | Idle | Front sprite, breathing bob, blink |');
line('| Hero | Selection | Front sprite, hop and lean, `celebrate` face |');
line('| Hero | Driving | `rear`, `mid`, then `turn` (mirrored for the other way) as it swings across, on a springy lean with a little squash; the cap trails the turn |');
line('| Hero | Signature | Rear sprite plus the signature\'s own road effect; `determined` face in callouts |');
line('| Hero | Hit | Short shake and tint; `hurt` face in callouts |');
line('| Hero | Victory | Front sprite, `celebrate` face on the results screen |');
line('| Sidekick | Idle | Front sprite with its own bob, speed, squash, tilt and sway (`RHYTHM`, `SWAY` in `web/art/clay.ts`) |');
line('| Sidekick | Following | Rear sprite beside the car: flyers float, road ones hop; its tilt trails the car and what stands above the body sways |');
line('| Sidekick | Assisting | Lift, squash and its own small flourish (`web/render/sidekickFx.ts`); the status tile turns gold with a diamond mark |');
line('| Sidekick | Recovering | Status ring refills, tile desaturates, the dot goes away |');
line('| Sidekick | Celebrating | `celebrate` face at reveals and results |');
line();
line('## Heroes');
for (const id of HEROES) {
  const d = HERO_DEFS[id];
  const lookNow = look(polish(heroScenes.HEROES[id].parts()));
  line();
  line(`### ${d.name} (\`${id}\`)`);
  line();
  line(`- **Identity:** ${d.role}. ${d.bio}`);
  line(`- **Silhouette:** ${NOTES[id] ?? ''}`);
  line(`- **Palette:** ${lookNow.palette}`);
  line(`- **Materials:** ${lookNow.materials}`);
  line(`- **Signature:** ${d.signature.name}, ${d.signature.cooldown} s. ${d.signature.short}`);
  line(`- **Earned by:** ${howToEarn(heroRule(id), d.unlock?.text ?? 'From the start.')}`);
  line(`- **Views:** ${sprite(`h.${id}.rear`)}; ${sprite(`h.${id}.mid`)}; ${sprite(`h.${id}.turn`)}; ${sprite(`h.${id}.face`)}; ${sprite(`h.${id}.front`)}; ${sprite(`h.${id}.q`)}; ${sprite(`h.${id}.q2`)}. Width ${manifest[`h.${id}.rear`].wide ?? '?'} units.`);
  line(`- **Files:** \`frontend/games/roadTrip/assets/art/h.${id}.{rear,mid,turn,face,front,q,q2}.webp\`; model in \`scripts/tollbound-art/scenes/${id === 'navie' ? 'navie' : 'heroes'}.js\``);
}
line();
line('## Companions');
for (const id of SIDEKICKS) {
  const d = SIDEKICK_DEFS[id];
  const lookNow = look(polish(sidekickScenes.SIDEKICKS[id].make(false)));
  line();
  line(`### ${d.name} (\`${id}\`), evolves into ${d.evolvedName}`);
  line();
  line(`- **Identity:** ${d.roleLabel}. ${d.blurb}`);
  line(`- **Silhouette:** ${NOTES[id] ?? ''}`);
  line(`- **Palette:** ${lookNow.palette}`);
  line(`- **Materials:** ${lookNow.materials}`);
  line(`- **Tags:** ${sidekickTags(id).join(', ')}`);
  line(`- **Earned by:** ${howToEarn(sidekickRule(id), d.unlock?.text ?? 'From the start.')}`);
  line(`- **Views:** ${sprite(`s.${id}.face`)}; ${sprite(`s.${id}.front`)}; ${sprite(`s.${id}.q`)}; ${sprite(`s.${id}.evo`)}; ${sprite(`s.${id}.rear`)}.`);
  line(`- **Files:** \`frontend/games/roadTrip/assets/art/s.${id}.{face,front,q,evo,rear}.webp\`; model in \`scripts/tollbound-art/scenes/sidekicks.js\``);
}
line();
fs.writeFileSync(path.join(artDir, 'BRIEFS.md'), lines.join('\n'));
fs.rmSync(out, { recursive: true, force: true });
console.log(`Wrote assets/art/BRIEFS.md: ${HEROES.length} heroes, ${SIDEKICKS.length} companions.`);
