#!/usr/bin/env node
/**
 * Copies Navie, the app's own mascot, into NLEX: Wildway Guardians: smaller copies of
 * the existing PNGs in frontend/assets, written as data URIs to
 * frontend/games/wildway/web/navieArt.ts. Navie is never redrawn: this only resizes the
 * images, with a plain area-average so the colours stay exactly Navie's.
 *
 *   node scripts/prepare-wildway-art.js
 *
 * Run it again only if the mascot images in frontend/assets change.
 */
const fs = require('fs');
const path = require('path');
const { PNG } = require('pngjs');

const repo = path.join(__dirname, '..');
const assets = path.join(repo, 'frontend', 'assets');
const out = path.join(repo, 'frontend', 'games', 'wildway', 'web', 'navieArt.ts');

/** Area-average downscale to fit inside `size`, keeping the aspect ratio. */
function shrink(file, size) {
  const src = PNG.sync.read(fs.readFileSync(path.join(assets, file)));
  const k = Math.min(1, size / Math.max(src.width, src.height));
  const w = Math.max(1, Math.round(src.width * k));
  const h = Math.max(1, Math.round(src.height * k));
  const dst = new PNG({ width: w, height: h });
  for (let y = 0; y < h; y += 1) {
    for (let x = 0; x < w; x += 1) {
      const x0 = Math.floor((x * src.width) / w);
      const x1 = Math.max(x0 + 1, Math.floor(((x + 1) * src.width) / w));
      const y0 = Math.floor((y * src.height) / h);
      const y1 = Math.max(y0 + 1, Math.floor(((y + 1) * src.height) / h));
      let r = 0;
      let g = 0;
      let b = 0;
      let a = 0;
      let n = 0;
      for (let sy = y0; sy < y1; sy += 1) {
        for (let sx = x0; sx < x1; sx += 1) {
          const i = (sy * src.width + sx) * 4;
          const alpha = src.data[i + 3];
          /* Weight colour by alpha, so transparent edges do not darken the outline. */
          r += src.data[i] * alpha;
          g += src.data[i + 1] * alpha;
          b += src.data[i + 2] * alpha;
          a += alpha;
          n += 1;
        }
      }
      const o = (y * w + x) * 4;
      dst.data[o] = a > 0 ? Math.round(r / a) : 0;
      dst.data[o + 1] = a > 0 ? Math.round(g / a) : 0;
      dst.data[o + 2] = a > 0 ? Math.round(b / a) : 0;
      dst.data[o + 3] = Math.round(a / n);
    }
  }
  return { uri: `data:image/png;base64,${PNG.sync.write(dst).toString('base64')}`, w, h };
}

const art = {
  hello: shrink('mascot-hello.png', 256),
  alert: shrink('mascot-alert.png', 128),
  clear: shrink('mascot-clear.png', 128),
  thinking: shrink('mascot-thinking.png', 128),
  traffic: shrink('mascot-traffic.png', 128),
};

const body = Object.entries(art)
  .map(([k, v]) => `  ${k}: { w: ${v.w}, h: ${v.h}, uri: '${v.uri}' },`)
  .join('\n');
fs.writeFileSync(
  out,
  `/* Generated by scripts/prepare-wildway-art.js from frontend/assets/mascot-*.png. Do not edit. */

/** Navie, SmartFlow NLEX's mascot, as the app draws it: resized copies, never redrawn. */
export const NAVIE_ART = {
${body}
};

export type NavieMood = keyof typeof NAVIE_ART;
`,
);
const kb = (fs.statSync(out).size / 1024).toFixed(0);
console.log(`Wrote ${path.relative(repo, out)} (${kb} KB): ${Object.entries(art).map(([k, v]) => `${k} ${v.w}x${v.h}`).join(', ')}`);
