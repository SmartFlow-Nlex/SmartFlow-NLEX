import type { DayDef } from './days';
import { carKmFor } from './factors';
import { PERKS, type PerkId } from './perks';
import { createRng } from './rng';
import { applyPerk, createSim, runUnmanaged, type Sim } from './sim';

/**
 * One whole shift: the budget, the comparison with nobody managing the plaza, the
 * changes picked along the way and the stars at the end.
 */

export interface Unmanaged {
  total: number;
  byClass: [number, number, number];
  /** kg by second. */
  trace: number[];
  longestQueue: number;
}

export interface ShiftRun {
  def: DayDef;
  unmanaged: Unmanaged;
  /** kg: reach this and the shift ends. */
  budget: number;
}

export interface ShiftOutcome {
  /** False when the budget ran out before the shift ended. */
  finished: boolean;
  /** kg generated. */
  used: number;
  /** What nobody managing would have generated over the same time. */
  unmanaged: number;
  /** kg avoided. */
  saved: number;
  /** Avoided as a share of unmanaged, 0-1. */
  share: number;
  stars: 0 | 1 | 2 | 3;
  byClass: [number, number, number];
  arrivedByClass: [number, number, number];
  carKm: number;
  /** Seconds left on the countdown when the budget ran out; null if it did not. */
  smogLeft: number | null;
  moves: number;
  reliefs: number;
  longestQueue: number;
  unmanagedLongestQueue: number;
  emergencies: number;
  handled: number;
}

export function computeUnmanaged(def: DayDef): Unmanaged {
  const run = runUnmanaged(def, { seed: def.seed });
  return { total: run.total, byClass: run.byClass, trace: run.trace, longestQueue: run.longestQueue };
}

export function startShift(def: DayDef): ShiftRun {
  const unmanaged = computeUnmanaged(def);
  return { def, unmanaged, budget: unmanaged.total * (1 - def.need[0]) };
}

export const startSim = (run: ShiftRun, listen = true): Sim => createSim(run.def, { seed: run.def.seed, listen });

export const budgetGone = (run: ShiftRun, sim: Sim): boolean => sim.co2 >= run.budget;

/** What nobody managing would have generated by this moment. */
export function unmanagedAt(run: ShiftRun, seconds: number): number {
  const trace = run.unmanaged.trace;
  const whole = Math.floor(seconds);
  if (whole >= trace.length - 1) {
    return run.unmanaged.total;
  }
  const k = seconds - whole;
  return trace[whole] + (trace[whole + 1] - trace[whole]) * k;
}

/** Two changes to pick from after a wave, always the same for the same shift and wave. */
export function perkOffers(run: ShiftRun, sim: Sim, afterWave: number): PerkId[] {
  const rng = createRng(run.def.seed + (afterWave + 1) * 104729);
  const hasEngines = run.def.engines > 0;
  const pool = PERKS.map((p) => p.id).filter((id) => !sim.perks.includes(id) && (hasEngines || id !== 'engineCampaign'));
  const offers: PerkId[] = [];
  while (offers.length < 2 && pool.length > 0) {
    offers.push(pool.splice(Math.floor(rng.next() * pool.length), 1)[0]);
  }
  return offers;
}

export const pickPerk = (sim: Sim, id: PerkId): void => applyPerk(sim, id);

export function starsFor(def: DayDef, share: number): 0 | 1 | 2 | 3 {
  if (share >= def.need[2]) {
    return 3;
  }
  if (share >= def.need[1]) {
    return 2;
  }
  return share >= def.need[0] ? 1 : 0;
}

/**
 * The shift's result. If the budget ran out, the comparison stops at that same
 * moment, so it stays like for like, and there are no stars.
 */
export function outcome(run: ShiftRun, sim: Sim, smog: boolean): ShiftOutcome {
  const used = sim.co2;
  const unmanaged = smog ? unmanagedAt(run, sim.t) : run.unmanaged.total;
  const saved = Math.max(0, unmanaged - used);
  return {
    finished: !smog,
    used,
    unmanaged,
    saved,
    share: unmanaged > 0 ? saved / unmanaged : 0,
    stars: smog ? 0 : starsFor(run.def, 1 - used / run.unmanaged.total),
    byClass: [sim.co2ByClass[0], sim.co2ByClass[1], sim.co2ByClass[2]],
    arrivedByClass: [sim.arrivedByClass[0], sim.arrivedByClass[1], sim.arrivedByClass[2]],
    carKm: carKmFor(saved),
    smogLeft: smog ? Math.max(0, Math.ceil(sim.duration - sim.t)) : null,
    moves: sim.moves,
    reliefs: sim.reliefs,
    longestQueue: sim.longestQueue,
    unmanagedLongestQueue: run.unmanaged.longestQueue,
    emergencies: sim.emergencies,
    handled: sim.handled,
  };
}
